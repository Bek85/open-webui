# Apply translations to a JSON file
# ---------------------------------------------------------------------------
def update_file(path: str, corrections: dict, additions: dict, use_cyrl: bool):
    with open(path, encoding='utf-8') as f:
        data = json.load(f)

    changed = 0

    # Apply corrections (fix wrong existing translations)
    for key, latn_val in corrections.items():
        val = latn_to_cyrl(latn_val) if use_cyrl else latn_val
        if key in data and data[key] != val:
            data[key] = val
            changed += 1

    # Apply new translations (only where current value is empty string)
    for key, latn_val in additions.items():
        if key in data and data[key] == '':
            val = latn_to_cyrl(latn_val) if use_cyrl else latn_val
            data[key] = val
            changed += 1

    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent='\t')
        f.write('\n')

    print(f"{'Cyrillic' if use_cyrl else 'Latin':8s}  {path}  →  {changed} keys updated")
    return changed


