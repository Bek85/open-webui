# Uzbek Latin → Cyrillic converter
# ---------------------------------------------------------------------------
def _convert_chunk(text: str) -> str:
    """Convert a plain Uzbek Latin text chunk to Cyrillic."""
    result = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        lo = ch.lower()
        upper = ch.isupper()
        rest2 = text[i:i+2].lower() if i + 1 < n else ""
        rest3 = text[i:i+3].lower() if i + 2 < n else ""

        # o' and g' (with apostrophe or right single quotation mark ʻ)
        if lo == 'o' and i + 1 < n and text[i+1] in ("'", "ʼ", "‘", "’", "ʹ"):
            result.append('Ў' if upper else 'ў')
            i += 2
        elif lo == 'g' and i + 1 < n and text[i+1] in ("'", "ʼ", "‘", "’", "ʹ"):
            result.append('Ғ' if upper else 'ғ')
            i += 2
        # digraphs
        elif rest2 == 'sh':
            result.append('Ш' if upper else 'ш')
            i += 2
        elif rest2 == 'ch':
            result.append('Ч' if upper else 'ч')
            i += 2
        elif rest2 == 'ng':
            result.append('Н' if upper else 'н')
            result.append('г')  # always lowercase for the second part
            i += 2
        # y-combos (start of word or after non-letter)
        elif lo == 'y' and i + 1 < n:
            nxt = text[i+1].lower()
            if nxt == 'a':
                result.append('Я' if upper else 'я')
                i += 2
            elif nxt == 'u':
                result.append('Ю' if upper else 'ю')
                i += 2
            elif nxt == 'o':
                result.append('Ё' if upper else 'ё')
                i += 2
            elif nxt == 'e':
                result.append('Е' if upper else 'е')
                i += 2
            else:
                result.append('Й' if upper else 'й')
                i += 1
        # single chars
        else:
            MAP = {
                'a': 'а', 'b': 'б', 'd': 'д', 'e': 'е', 'f': 'ф',
                'g': 'г', 'h': 'ҳ', 'i': 'и', 'j': 'ж', 'k': 'к',
                'l': 'л', 'm': 'м', 'n': 'н', 'o': 'о', 'p': 'п',
                'q': 'қ', 'r': 'р', 's': 'с', 't': 'т', 'u': 'у',
                'v': 'в', 'x': 'х', 'y': 'й', 'z': 'з',
            }
            if lo in MAP:
                c = MAP[lo]
                result.append(c.upper() if upper else c)
            else:
                result.append(ch)
            i += 1
    return ''.join(result)


def latn_to_cyrl(text: str) -> str:
    """Convert Uzbek Latin text to Cyrillic, preserving template vars and punctuation."""
    if not text:
        return text
    # Split on template vars {{...}}, URLs, and markdown formatting
    parts = re.split(r'(\{\{[^}]+\}\}|https?://\S+|`[^`]+`|\*\*[^*]+\*\*)', text)
    result = []
    for part in parts:
        if re.match(r'\{\{[^}]+\}\}|https?://\S+|`[^`]+`|\*\*[^*]+\*\*', part):
            result.append(part)  # preserve as-is
        else:
            result.append(_convert_chunk(part))
    return ''.join(result)


